//! Every protocol says how much of a connection's history the model sees, and whether events
//! arriving during a call are batched.
//!
//! Both have safe builder defaults — history off, batching unsupported — and that is exactly
//! why a declaration is required: a default cannot tell "someone decided this protocol's
//! events stand alone" from "nobody thought about it", and the second one is how a telnet
//! server came to answer "what did I just say?" from a prompt holding only that question.
//!
//! This reads source rather than walking the registry, so it holds at any feature set and
//! for every protocol, compiled in or not. It counts declarations per `metadata()`
//! implementation, because one `actions.rs` can implement several (`h323`'s gatekeeper and
//! endpoint), and it accepts the three forms metadata is written in:
//!
//! - the builder: `.history(…)` / `.batching(…)`;
//! - a struct literal: `history: …` / `batching: …` (`src/client/ospf/actions.rs`);
//! - assignment onto metadata borrowed from another protocol: `m.history = …`
//!   (`src/client/gnmi/actions.rs`).
//!
//! A missed form fails the safe way — it reads as "declares nothing" and is reported — so a
//! false positive costs a reader a minute rather than a protocol its history.
//!
//! Run with:
//!   ./cargo-isolated.sh test --test history_batching_declaration_test

use std::path::{Path, PathBuf};

/// `//` comments removed, so a sentence about `.history(` is not a declaration.
///
/// Only a `//` outside a string literal starts a comment: `src/client/docker/actions.rs`
/// writes `"unix:///absolute/socket"` in its notes on the same line as its declaration, and
/// cutting there hid the declaration.
fn strip_comments(source: &str) -> String {
    source
        .lines()
        .map(|line| {
            let bytes = line.as_bytes();
            let mut in_string = false;
            let mut i = 0;
            while i < bytes.len() {
                match bytes[i] {
                    b'\\' if in_string => i += 1,
                    b'"' => in_string = !in_string,
                    b'/' if !in_string && bytes.get(i + 1) == Some(&b'/') => return &line[..i],
                    _ => {}
                }
                i += 1;
            }
            line
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// Every `actions.rs` under `src/<tree>/`, one level of nesting included (`usb/serial`).
fn action_files(tree: &str) -> Vec<PathBuf> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("src").join(tree);
    let mut files = Vec::new();
    for entry in std::fs::read_dir(&root).expect("read protocol tree") {
        let dir = entry.expect("dir entry").path();
        if !dir.is_dir() {
            continue;
        }
        let direct = dir.join("actions.rs");
        if direct.is_file() {
            files.push(direct);
        }
        for nested in std::fs::read_dir(&dir).expect("read protocol dir") {
            let nested = nested.expect("nested entry").path().join("actions.rs");
            if nested.is_file() {
                files.push(nested);
            }
        }
    }
    files.sort();
    files
}

/// How many metadata implementations a file holds: trait methods and the free functions
/// some families build theirs with (`inetd`'s per-service `metadata(service)`).
fn metadata_impls(source: &str) -> usize {
    source.matches("fn metadata(").count()
}

fn declarations(source: &str, field: &str) -> usize {
    let builder = source.matches(&format!(".{field}(")).count();
    let literal = source
        .matches(&format!("{field}: crate::protocol::metadata::"))
        .count()
        + source.matches(&format!("{field}: HistoryMode::")).count()
        + source.matches(&format!("{field}: BatchingMode::")).count();
    let assigned = source.matches(&format!(".{field} = ")).count();
    builder + literal + assigned
}

/// Implementations whose `metadata()` hands back another one unchanged, so the declaration
/// lives with the protocol it delegates to. Each entry names where.
const DELEGATES: &[(&str, &str)] = &[
    // The per-service trait impls generated by the macro call the free
    // `metadata(service)` in the same file, which declares both.
    (
        "client/inetd/actions.rs",
        "macro-generated impls call metadata(service) above",
    ),
    (
        "server/inetd/actions.rs",
        "macro-generated impls call metadata(service) above",
    ),
];

fn check(tree: &str) -> (usize, Vec<String>) {
    let files = action_files(tree);
    let mut checked = 0;
    let mut missing = Vec::new();
    for file in &files {
        let source = strip_comments(&std::fs::read_to_string(file).expect("read actions.rs"));
        let mut impls = metadata_impls(&source);
        if impls == 0 {
            continue;
        }
        let rel = file
            .strip_prefix(Path::new(env!("CARGO_MANIFEST_DIR")).join("src"))
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/");
        if DELEGATES.iter().any(|(path, _)| *path == rel) {
            // The free function declares once for every generated impl.
            impls = 1;
        }
        checked += 1;
        for field in ["history", "batching"] {
            let found = declarations(&source, field);
            if found < impls {
                missing.push(format!(
                    "{rel}: {impls} metadata implementation(s), {found} `{field}` declaration(s)"
                ));
            }
        }
    }
    (checked, missing)
}

#[test]
fn every_protocol_declares_history_and_batching() {
    let mut all_missing = Vec::new();
    for (tree, floor) in [("server", 250), ("client", 200)] {
        let (checked, missing) = check(tree);
        // A scan that found nothing would pass vacuously.
        assert!(
            checked >= floor,
            "only {checked} {tree} actions.rs files with metadata() were found; the scan is \
             not reaching the protocol tree (expected at least {floor})"
        );
        all_missing.extend(missing);
    }
    assert!(
        all_missing.is_empty(),
        "these protocols do not declare history and/or batching in metadata():\n  {}\n\n\
         Add `.history(HistoryMode::Off)` where each event stands alone (DNS, HTTP, lookups, \
         datagrams) or `.history(HistoryMode::Last(SESSION_HISTORY_ENTRIES))` where a peer's \
         next message is read in the light of its last; and `.batching(BatchingMode::Unsupported)` \
         unless the protocol delivers events that arrive during a call together afterwards — \
         see `src/protocol/metadata.rs`.",
        all_missing.join("\n  ")
    );
}

/// The counting must see a declaration in each form, or the check above is measuring nothing.
#[test]
fn the_scan_recognises_each_declaration_form() {
    let builder = ".history(crate::protocol::metadata::HistoryMode::Off)";
    let literal = "history: HistoryMode::Last(SESSION_HISTORY_ENTRIES),";
    let assigned = "m.history = crate::protocol::metadata::HistoryMode::Off;";
    let comment = "// .history(HistoryMode::Off) is what a datagram protocol declares";
    let url_in_string = r#".notes("see unix:///run/x").history(HistoryMode::Off)"#;
    assert_eq!(
        declarations(&strip_comments(url_in_string), "history"),
        1,
        "a `//` inside a string literal must not start a comment"
    );
    for form in [builder, literal, assigned] {
        assert_eq!(declarations(&strip_comments(form), "history"), 1, "{form}");
    }
    assert_eq!(
        declarations(&strip_comments(comment), "history"),
        0,
        "a comment must not count as a declaration"
    );
}
