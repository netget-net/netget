//! The TUN/TAP packet layer, against literal packet bytes.
//!
//! Creating a TUN interface needs root, so the transport can never run here. What *can* run —
//! and is where every decision about what NetGet says lives — is the decoder, the builder and
//! the escalation filter. So they are tested against real header bytes written out by hand,
//! not against anything this code produced.
//!
//! Run with:
//!   ./cargo-isolated.sh test --no-default-features --features tuntap \
//!       --test server -- server::tuntap::packet_test --test-threads=100

