    #[test]
    fn refuses_the_packets_it_cannot_honestly_build() {
        let cases: Vec<(&str, serde_json::Value)> = vec![
            (
                "mixed address families",
                json!({"source": "10.0.0.1", "destination": "2001:db8::1", "protocol": "udp",
                       "source_port": 1, "destination_port": 2}),
            ),
            (
                "icmp over IPv6",
                json!({"source": "2001:db8::1", "destination": "2001:db8::2",
                       "protocol": "icmp", "icmp_type": "echo_reply"}),
            ),
            (
                "icmpv6 over IPv4",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2",
                       "protocol": "icmpv6", "icmp_type": "echo_reply"}),
            ),
            (
                "ip_version contradicting the addresses",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "icmp",
                       "icmp_type": "echo_reply", "ip_version": 6}),
            ),
            (
                "an unknown protocol name",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "quux"}),
            ),
            (
                "an unknown TCP flag",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "tcp",
                       "source_port": 1, "destination_port": 2, "flags": ["synn"]}),
            ),
            (
                "TCP without ports",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "tcp"}),
            ),
            (
                "ICMP without a type",
                json!({"source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "icmp"}),
            ),
            (
                "no source at all",
                json!({"destination": "10.0.0.2", "protocol": "icmp", "icmp_type": "echo_reply"}),
            ),
        ];

        for (why, action) in cases {
            assert!(
                build_packet(&action).is_err(),
                "{why} must be refused — guessing here would put a packet on a real \
                 interface that nobody described"
            );
        }
    }

