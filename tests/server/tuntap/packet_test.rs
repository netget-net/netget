    /// IPv4 / ICMP echo request, 10.7.0.1 -> 10.7.0.2, id 0x1234, seq 1, payload "abcdefgh".
    ///
    /// 20-byte IP header + 8-byte ICMP header + 8-byte payload = 36 = 0x0024.
    fn ipv4_icmp_echo_request() -> Vec<u8> {
        vec![
            // ---- IPv4 ----
            0x45, // version 4, IHL 5
            0x00, // DSCP/ECN
            0x00, 0x24, // total length 36
            0xab, 0xcd, // identification
            0x40, 0x00, // flags: DF, fragment offset 0
            0x40, // TTL 64
            0x01, // protocol 1 = ICMP
            0x00, 0x00, // header checksum (not verified on decode)
            0x0a, 0x07, 0x00, 0x01, // src 10.7.0.1
            0x0a, 0x07, 0x00, 0x02, // dst 10.7.0.2
            // ---- ICMP ----
            0x08, // type 8 = echo request
            0x00, // code 0
            0x00, 0x00, // checksum
            0x12, 0x34, // identifier 4660
            0x00, 0x01, // sequence 1
            // ---- payload "abcdefgh" ----
            0x61, 0x62, 0x63, 0x64, 0x65, 0x66, 0x67, 0x68,
        ]
    }

    /// IPv4 / TCP SYN, 192.168.1.100:54321 -> 192.168.1.1:80, seq 1, window 65535.
    fn ipv4_tcp_syn() -> Vec<u8> {
        vec![
            0x45, 0x00, 0x00, 0x28, // total length 40 = 20 + 20
            0x00, 0x01, 0x40, 0x00, 0x40, //
            0x06, // protocol 6 = TCP
            0x00, 0x00, //
            0xc0, 0xa8, 0x01, 0x64, // src 192.168.1.100
            0xc0, 0xa8, 0x01, 0x01, // dst 192.168.1.1
            // ---- TCP ----
            0xd4, 0x31, // source port 54321
            0x00, 0x50, // destination port 80
            0x00, 0x00, 0x00, 0x01, // seq 1
            0x00, 0x00, 0x00, 0x00, // ack 0
            0x50, // data offset 5 words, reserved 0
            0x02, // flags: SYN
            0xff, 0xff, // window 65535
            0x00, 0x00, // checksum
            0x00, 0x00, // urgent pointer
        ]
    }

    /// The same flow's SYN+ACK, which `tcp-syn` must NOT match.
    fn ipv4_tcp_syn_ack() -> Vec<u8> {
        let mut p = ipv4_tcp_syn();
        p[33] = 0x12; // SYN | ACK
        p
    }

    /// IPv4 / UDP, 10.0.0.1:40481 -> 8.8.8.8:53, payload "hello".
    fn ipv4_udp() -> Vec<u8> {
        vec![
            0x45, 0x00, 0x00, 0x21, // total length 33 = 20 + 8 + 5
            0x00, 0x02, 0x00, 0x00, 0x40, //
            0x11, // protocol 17 = UDP
            0x00, 0x00, //
            0x0a, 0x00, 0x00, 0x01, // src 10.0.0.1
            0x08, 0x08, 0x08, 0x08, // dst 8.8.8.8
            // ---- UDP ----
            0x9e, 0x21, // source port 40481
            0x00, 0x35, // destination port 53
            0x00, 0x0d, // length 13 = 8 + 5
            0x00, 0x00, // checksum
            0x68, 0x65, 0x6c, 0x6c, 0x6f, // "hello"
        ]
    }

    /// IPv6 / ICMPv6 echo request, 2001:db8::1 -> 2001:db8::2, id 0xabcd, seq 7.
    fn ipv6_icmpv6_echo_request() -> Vec<u8> {
        vec![
            0x60, 0x00, 0x00, 0x00, // version 6, no traffic class or flow label
            0x00, 0x10, // payload length 16 = 8 + 8
            0x3a, // next header 58 = ICMPv6
            0x40, // hop limit 64
            // src 2001:db8::1
            0x20, 0x01, 0x0d, 0xb8, 0x00, 0x00, 0x00, 0x00, //
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, //
            // dst 2001:db8::2
            0x20, 0x01, 0x0d, 0xb8, 0x00, 0x00, 0x00, 0x00, //
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, //
            // ---- ICMPv6 ----
            0x80, // type 128 = echo request
            0x00, // code 0
            0x00, 0x00, // checksum
            0xab, 0xcd, // identifier 43981
            0x00, 0x07, // sequence 7
            0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, // "12345678"
        ]
    }

    fn tun(frame: &[u8]) -> Result<netget::server::tuntap::packet::DecodedPacket, DecodeError> {
        decode(frame, PacketInformation::None, LinkMode::Tun)
    }

