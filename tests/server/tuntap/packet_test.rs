    /// The `payload_encoding` field is honoured, not sniffed.
    ///
    /// `"48656c6c6f"` is simultaneously valid text and valid hex; only the sender knows which
    /// it meant. This is the `send_tcp_data` bug the root `CLAUDE.md` records, and it must not
    /// be reintroduced here.
    #[test]
    fn the_payload_encoding_field_decides_and_is_never_guessed() {
        let ambiguous = "48656c6c6f";

        let as_hex = build_packet(&json!({
            "source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "udp",
            "source_port": 1, "destination_port": 2,
            "payload": ambiguous, "payload_encoding": "hex"
        }))
        .expect("builds");
        assert_eq!(&as_hex[28..], b"Hello", "hex must actually be decoded");

        let as_text = build_packet(&json!({
            "source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "udp",
            "source_port": 1, "destination_port": 2,
            "payload": ambiguous, "payload_encoding": "utf8"
        }))
        .expect("builds");
        assert_eq!(
            &as_text[28..],
            ambiguous.as_bytes(),
            "the same string as text is ten bytes, not five"
        );

        let default = build_packet(&json!({
            "source": "10.0.0.1", "destination": "10.0.0.2", "protocol": "udp",
            "source_port": 1, "destination_port": 2,
            "payload": ambiguous
        }))
        .expect("builds");
        assert_eq!(&default[28..], ambiguous.as_bytes(), "the default is utf8");
    }

