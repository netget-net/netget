    #[test]
    fn builds_a_udp_datagram_with_a_valid_pseudo_header_checksum() {
        let bytes = build_packet(&json!({
            "source": "10.0.0.1",
            "destination": "10.0.0.2",
            "protocol": "udp",
            "source_port": 1234,
            "destination_port": 53,
            "payload": "hello"
        }))
        .expect("builds");

        let p = tun(&bytes).expect("decodes");
        assert_eq!(p.ports(), Some((1234, 53)));
        assert_eq!(p.payload_preview, "hello");
        assert!(checksum_is_valid(&bytes[..20]));

        // UDP's checksum covers the IPv4 pseudo-header followed by the datagram.
        let mut span = vec![
            10, 0, 0, 1, // source
            10, 0, 0, 2, // destination
            0, 17, // zero, protocol
        ];
        let udp = &bytes[20..];
        span.extend_from_slice(&(udp.len() as u16).to_be_bytes());
        span.extend_from_slice(udp);
        assert!(checksum_is_valid(&span));
    }

