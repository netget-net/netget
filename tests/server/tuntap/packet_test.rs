    fn matches(expr: &str, frame: &[u8]) -> bool {
        PacketFilter::parse(expr)
            .unwrap_or_else(|e| panic!("filter {expr:?} should parse: {e}"))
            .matches(&tun(frame).expect("fixture decodes"))
    }

    #[test]
    fn all_and_none_are_the_two_extremes() {
        assert!(matches("all", &ipv4_icmp_echo_request()));
        assert!(matches("all", &ipv4_tcp_syn()));
        assert!(!matches("none", &ipv4_icmp_echo_request()));
        assert!(PacketFilter::parse("none").unwrap().matches_nothing());
        assert!(!PacketFilter::parse("all").unwrap().matches_nothing());
    }

    #[test]
    fn the_default_filter_admits_pings_and_nothing_else() {
        assert!(matches("icmp", &ipv4_icmp_echo_request()));
        assert!(!matches("icmp", &ipv4_tcp_syn()));
        assert!(!matches("icmp", &ipv4_udp()));
        assert!(
            !matches("icmp", &ipv6_icmpv6_echo_request()),
            "icmp is protocol 1; ICMPv6 is 58 and must be asked for by name"
        );
        assert!(matches("icmpv6", &ipv6_icmpv6_echo_request()));
    }

    /// `tcp-syn` is the term that makes the whole design work at TCP volume: one event per
    /// connection attempt rather than one per packet.
    #[test]
    fn tcp_syn_matches_a_new_connection_and_not_the_rest_of_it() {
        assert!(matches("tcp-syn", &ipv4_tcp_syn()));
        assert!(
            !matches("tcp-syn", &ipv4_tcp_syn_ack()),
            "SYN+ACK is the other side answering, not a new connection"
        );

        let mut established = ipv4_tcp_syn();
        established[33] = 0x10; // plain ACK
        assert!(!matches("tcp-syn", &established));
        established[33] = 0x18; // PSH|ACK — data on an open connection
        assert!(!matches("tcp-syn", &established));
    }

    #[test]
    fn ports_addresses_and_versions_all_filter() {
        assert!(matches("tcp:80", &ipv4_tcp_syn()));
        assert!(
            matches("tcp:54321", &ipv4_tcp_syn()),
            "either endpoint counts"
        );
        assert!(!matches("tcp:443", &ipv4_tcp_syn()));
        assert!(matches("udp:53", &ipv4_udp()));
        assert!(
            !matches("tcp:53", &ipv4_udp()),
            "the transport must match too"
        );
        assert!(matches("port:53", &ipv4_udp()));

        assert!(matches("to:10.7.0.2", &ipv4_icmp_echo_request()));
        assert!(!matches("to:10.7.0.1", &ipv4_icmp_echo_request()));
        assert!(matches("from:10.7.0.1", &ipv4_icmp_echo_request()));
        assert!(matches("host:10.7.0.2", &ipv4_icmp_echo_request()));
        assert!(matches("host:10.7.0.1", &ipv4_icmp_echo_request()));

        assert!(matches("v4", &ipv4_udp()));
        assert!(!matches("v6", &ipv4_udp()));
        assert!(matches("v6", &ipv6_icmpv6_echo_request()));

        assert!(matches("ip-proto-1", &ipv4_icmp_echo_request()));
        assert!(!matches("ip-proto-6", &ipv4_icmp_echo_request()));
    }

    #[test]
    fn plus_is_and_and_comma_is_or() {
        let expr = "tcp-syn+to:192.168.1.1, icmp";
        assert!(matches(expr, &ipv4_tcp_syn()), "a SYN to the named host");
        assert!(matches(expr, &ipv4_icmp_echo_request()), "or any ping");
        assert!(!matches(expr, &ipv4_udp()));
        assert!(
            !matches("tcp-syn+to:10.0.0.9", &ipv4_tcp_syn()),
            "both halves of an AND must hold"
        );
    }

    #[test]
    fn a_malformed_filter_is_refused_at_startup_with_a_useful_message() {
        for expr in [
            "",
            "wat",
            "icmp,,udp",
            "tcp:notaport",
            "from:notanaddress",
            "ip-proto-999",
            "icmp:80",
        ] {
            let err = PacketFilter::parse(expr)
                .expect_err(&format!("{expr:?} must not parse"))
                .to_string();
            assert!(
                !err.is_empty(),
                "a rejection has to say what was wrong with {expr:?}"
            );
        }
        // "icmp:80" is refused specifically because ICMP has no ports to match on.
        assert!(PacketFilter::parse("icmp:80")
            .unwrap_err()
            .contains("no ports"));
    }

