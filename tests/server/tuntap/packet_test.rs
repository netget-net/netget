    /// **The off-by-four, from both sides.**
    ///
    /// Getting this wrong is the single most common TUN bug, and the reason it costs a
    /// debugging pass is that it does not present as a misaligned header — every decoded field
    /// is simply wrong. Both mismatches must therefore be *errors*, not garbage.
    #[test]
    fn a_packet_information_mismatch_is_an_error_in_both_directions() {
        let mut prefixed = vec![0x00, 0x00, 0x00, 0x02];
        prefixed.extend_from_slice(&ipv4_icmp_echo_request());

        // Prefix present, configuration says there is none: the version nibble reads 0.
        assert!(
            matches!(
                decode(&prefixed, PacketInformation::None, LinkMode::Tun),
                Err(DecodeError::UnsupportedIpVersion(0))
            ),
            "reading a prefixed frame as bare must fail, not decode four bytes off"
        );

        // No prefix, configuration says there is one: 0x45000024 is neither AF_INET nor
        // AF_INET6, so the header is rejected rather than skipped.
        assert!(
            matches!(
                decode(
                    &ipv4_icmp_echo_request(),
                    PacketInformation::MacOsUtun,
                    LinkMode::Tun
                ),
                Err(DecodeError::BadPacketInformation { .. })
            ),
            "reading a bare frame as prefixed must fail, not swallow the first four bytes"
        );

        // A prefix naming something that is not IP is rejected too.
        let mut nonsense = vec![0x00, 0x00, 0x00, 0x07];
        nonsense.extend_from_slice(&ipv4_icmp_echo_request());
        assert!(matches!(
            decode(&nonsense, PacketInformation::MacOsUtun, LinkMode::Tun),
            Err(DecodeError::BadPacketInformation { .. })
        ));
    }

    #[test]
    fn the_prefix_written_back_matches_the_one_read() {
        for (pi, ipv6, expected) in [
            (PacketInformation::MacOsUtun, false, Some([0, 0, 0, 2])),
            (PacketInformation::MacOsUtun, true, Some([0, 0, 0, 30])),
            (
                PacketInformation::LinuxTunPi,
                false,
                Some([0, 0, 0x08, 0x00]),
            ),
            (
                PacketInformation::LinuxTunPi,
                true,
                Some([0, 0, 0x86, 0xdd]),
            ),
            (PacketInformation::None, false, None),
        ] {
            assert_eq!(pi.prefix_for(ipv6), expected, "{pi:?} ipv6={ipv6}");
        }

        // Round trip: prepend then strip gives back exactly the packet.
        let original = ipv4_icmp_echo_request();
        for pi in [
            PacketInformation::None,
            PacketInformation::MacOsUtun,
            PacketInformation::LinuxTunPi,
        ] {
            let mut framed = original.clone();
            pi.prepend(&mut framed).expect("prepends");
            assert_eq!(framed.len(), original.len() + pi.header_len());
            assert_eq!(pi.strip(&framed).expect("strips"), &original[..]);
        }
    }

