#!/usr/bin/env python3
"""Generate the landing-page stack pool from both registries, including gated protocols.

Run before deploying (site/deploy.sh does this), or use --check to detect stale data.
This reads source so hardware-specific protocols do not depend on the build host.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "site/js/protocol-stacks.js"
# Each registration's protocol id on the site (the identity the landing page's protocol table
# uses). Protocols are not Cargo features, so the id is recorded here: a new protocol adds a
# line for each of its registrations.
IDS = ROOT / "scripts/site_protocol_ids.json"


def declared_stacks(role):
    stacks = {}
    for path in sorted((ROOT / f"src/{role}").rglob("*.rs")):
        source = path.read_text()
        for block in re.split(r"\bimpl\s+", source):
            protocol = re.match(r"(?:\w+::)*Protocol\s+for\s+(\w+)\s*\{", block)
            if not protocol:
                continue
            method = re.search(r"fn stack_name\(&self\)[^{]*\{([^}]+)\}", block)
            if method:
                body = re.sub(r"//[^\n]*", "", method[1]).strip()
                literal = re.fullmatch(r'"([^"\n]+)"', body)
                if literal:
                    stacks[protocol[1]] = literal[1]

    # Inetd's six protocol implementations are expanded by macros. Their shared
    # Service enum declares the stacks; read those rather than duplicating them.
    service_source = (ROOT / "src/server/inetd/actions.rs").read_text()
    services = dict(re.findall(r'Service::(\w+) => "([^"\n]*>[^"\n]*)"', service_source))
    macro_source = (ROOT / f"src/{role}/inetd/actions.rs").read_text()
    for protocol, service in re.findall(
        r"inetd_(?:protocol|client)!\(\s*(\w+),\s*Service::(\w+)", macro_source
    ):
        stacks[protocol] = services[service]
    return stacks


def catalog():
    ids = json.loads(IDS.read_text())
    entries = set()
    for role in ("server", "client"):
        stacks = declared_stacks(role)
        source = (ROOT / f"src/protocol/{role}_registry.rs").read_text()
        registrations = list(re.finditer(
            r"self\.register\(Arc::new\(\s*crate::" + role + r"::((?:\w+::)*[A-Z]\w*)",
            source,
        ))
        if len(registrations) != source.count("self.register("):
            raise ValueError(f"Unrecognised {role} registration; update the stack generator")
        for registration in registrations:
            key = f"{role}::{registration[1]}"
            if key not in ids:
                raise ValueError(f"No site id for {key}: add it to {IDS.relative_to(ROOT)}")
            protocol = registration[1].split("::")[-1]
            if protocol not in stacks:
                raise ValueError(f"No literal stack for registered {role} {protocol}")
            entries.add((ids[key], stacks[protocol]))
    return sorted(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    entries = catalog()
    content = (
        "// Generated by scripts/site_protocol_stacks.py from both protocol registries.\n"
        "// Each entry is [protocol id, stack from base to application]. Do not edit by hand.\n"
        "export const protocolStacks = [\n"
        + "".join(f"    {json.dumps(entry)},\n" for entry in entries)
        + "];\n"
    )
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit("Stale protocol stacks: run python3 scripts/site_protocol_stacks.py")
    else:
        OUTPUT.write_text(content)
    print(f"Protocol stacks: {len(entries)} variants across {len({pid for pid, _ in entries})} protocols")


if __name__ == "__main__":
    main()
