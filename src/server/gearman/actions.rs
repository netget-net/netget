impl Server for GearmanProtocol {
    fn spawn(
        &self,
        ctx: crate::protocol::SpawnContext,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = anyhow::Result<std::net::SocketAddr>> + Send>,
    > {
        Box::pin(async move {
            let secs = |name: &str| -> anyhow::Result<Option<u64>> {
                Ok(ctx
                    .startup_params
                    .as_ref()
                    .map(|p| p.get_optional_u64(name))
                    .transpose()?
                    .flatten())
            };
            let first_byte_timeout_secs = secs("first_byte_timeout_secs")?;
            let idle_timeout_secs = secs("idle_timeout_secs")?;

            crate::server::gearman::GearmanServer::spawn_with_llm_actions(
                ctx.legacy_listen_addr(),
                ctx.llm_client,
                ctx.state,
                ctx.status_tx,
                ctx.server_id,
                first_byte_timeout_secs,
                idle_timeout_secs,
            )
            .await
        })
    }

    fn execute_action(&self, action: Value) -> Result<ActionResult> {
        let action_type = action
            .get("type")
            .and_then(|v| v.as_str())
            .context("Missing 'type' field in action")?;

        let work = match action_type {
            "complete_gearman_job" => Work::Complete(text(&action, "result")?.into_bytes()),
            "fail_gearman_job" => Work::Fail,
            "send_gearman_status" => {
                let numerator = number(&action, "numerator")?;
                let denominator = number(&action, "denominator")?;
                if numerator > denominator {
                    return Err(anyhow!(
                        "numerator ({numerator}) must not exceed denominator ({denominator})"
                    ));
                }
                Work::Status(numerator, denominator)
            }
            "send_gearman_data" => Work::Data(text(&action, "data")?.into_bytes()),
            "send_gearman_exception" => Work::Exception(text(&action, "text")?.into_bytes()),
            "send_gearman_error" => {
                let code = action
                    .get("code")
                    .and_then(Value::as_str)
                    .context("send_gearman_error needs 'code'")?;
                let text = action.get("text").and_then(Value::as_str).unwrap_or("");
                return Ok(ActionResult::Output(
                    wire::error(code, text).map_err(|e| anyhow!("send_gearman_error: {e}"))?,
                ));
            }
            "close_connection" => return Ok(ActionResult::CloseConnection),
            _ => return Err(anyhow!("Unknown Gearman action: {}", action_type)),
        };
        match action.get("job_handle").and_then(Value::as_str) {
            Some(handle) if !handle.is_empty() => {
                Ok(ActionResult::Output(work.render(handle.as_bytes())))
            }
            _ => Ok(ActionResult::Custom {
                name: WORK_RESULT.to_string(),
                data: work.to_json(),
            }),
        }
    }
}

/// One answer to a job, before it has a handle.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Work {
    Status(u64, u64),
    Data(Vec<u8>),
    Complete(Vec<u8>),
    Fail,
    Exception(Vec<u8>),
}

impl Work {
    pub fn render(&self, handle: &[u8]) -> Vec<u8> {
        match self {
            Work::Status(n, d) => wire::work_status(handle, *n, *d),
            Work::Data(data) => wire::work_data(handle, data),
            Work::Complete(result) => wire::work_complete(handle, result),
            Work::Fail => wire::work_fail(handle),
            Work::Exception(text) => wire::work_exception(handle, text),
        }
    }

    fn to_json(&self) -> Value {
        let text = |b: &[u8]| String::from_utf8_lossy(b).into_owned();
        match self {
            Work::Status(n, d) => json!({"kind": "status", "numerator": n, "denominator": d}),
            Work::Data(data) => json!({"kind": "data", "data": text(data)}),
            Work::Complete(result) => json!({"kind": "complete", "result": text(result)}),
            Work::Fail => json!({"kind": "fail"}),
            Work::Exception(t) => json!({"kind": "exception", "text": text(t)}),
        }
    }

    /// Read back what [`Work::to_json`] produced.
    pub fn from_json(value: &Value) -> Option<Work> {
        let s = |k: &str| {
            value
                .get(k)
                .and_then(Value::as_str)
                .map(|s| s.as_bytes().to_vec())
        };
        Some(match value.get("kind")?.as_str()? {
            "status" => Work::Status(
                value.get("numerator")?.as_u64()?,
                value.get("denominator")?.as_u64()?,
            ),
            "data" => Work::Data(s("data")?),
            "complete" => Work::Complete(s("result")?),
            "fail" => Work::Fail,
            "exception" => Work::Exception(s("text")?),
            _ => return None,
        })
    }
}

fn text(action: &Value, name: &str) -> Result<String> {
    match action.get(name) {
        Some(Value::String(s)) => Ok(s.clone()),
        Some(Value::Number(n)) => Ok(n.to_string()),
        None | Some(Value::Null) => Ok(String::new()),
        Some(_) => Err(anyhow!("'{name}' must be text")),
    }
}

fn number(action: &Value, name: &str) -> Result<u64> {
    action
        .get(name)
        .and_then(|v| {
            v.as_u64()
                .or_else(|| v.as_str().and_then(|s| s.trim().parse().ok()))
        })
        .with_context(|| format!("'{name}' must be a non-negative integer"))
}

