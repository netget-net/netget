impl Server for EapolProtocol {
    fn spawn(
        &self,
        ctx: crate::protocol::SpawnContext,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = anyhow::Result<std::net::SocketAddr>> + Send>,
    > {
        Box::pin(async move { super::EapolServer::spawn_with_llm_actions(ctx).await })
    }

    /// Encode exactly the frame a named action asked for.
    ///
    /// Read the module header before changing anything here. In particular: there is no
    /// wildcard arm that produces a frame, `send_eap_success` is the only path to
    /// [`codec::eapol_eap_success_frame`], and that path is gated on `identity_established`.
    fn execute_action(&self, action: serde_json::Value) -> Result<ActionResult> {
        let action_type = action
            .get("type")
            .and_then(|v| v.as_str())
            .context("Missing 'type' field in action")?;

        // Resolve the name before the context, so an action this protocol does not have is
        // reported as *unknown* rather than as a missing request. Both are refusals, but only
        // one of them tells a model it guessed a verb that does not exist — and
        // `tests/event_action_declarations_test.rs` detects an unexecutable advertised name
        // by exactly that wording. Taking the context first made the `_` arm unreachable on a
        // registry instance and hid the difference.
        if !matches!(
            action_type,
            "send_eap_request_identity"
                | "send_eap_request_method"
                | "send_eap_notification"
                | "send_eap_success"
                | "send_eap_failure"
        ) {
            return Err(anyhow::anyhow!("Unknown EAPOL action: {}", action_type));
        }

        // Every remaining arm needs the request context, so take it once: a registry instance
        // fails here rather than half-building a frame with an invented identifier.
        let ctx = self.ctx()?;

        match action_type {
            "send_eap_request_identity" => Ok(ActionResult::Output(
                codec::eapol_wrap_eap(
                    ctx.eapol_version,
                    &codec::eap_request_identity(ctx.request_identifier),
                )
                .map_err(|e| anyhow::anyhow!("Failed to encode EAPOL frame: {}", e))?,
            )),

            "send_eap_request_method" => {
                let eap_type = method_type_value(
                    action
                        .get("eap_type")
                        .context("send_eap_request_method requires 'eap_type'")?,
                )?;

                let eap = match eap_type {
                    codec::EAP_TYPE_MD5_CHALLENGE => codec::eap_request_md5_challenge(
                        ctx.request_identifier,
                        &ctx.md5_challenge,
                        AUTHENTICATOR_NAME,
                    ),
                    other => codec::eap_request_tls_start(ctx.request_identifier, other),
                }
                .map_err(|e| anyhow::anyhow!("Failed to encode EAP-Request: {}", e))?;

                Ok(ActionResult::Output(
                    codec::eapol_wrap_eap(ctx.eapol_version, &eap)
                        .map_err(|e| anyhow::anyhow!("Failed to encode EAPOL frame: {}", e))?,
                ))
            }

            "send_eap_notification" => {
                let text = required_text(&action, "text")?;
                if text.is_empty() {
                    return Err(anyhow::anyhow!(
                        "send_eap_notification 'text' must not be empty: an empty notification \
                         tells the supplicant nothing and still costs a round trip"
                    ));
                }
                let eap = codec::eap_request_notification(ctx.request_identifier, &text)
                    .map_err(|e| anyhow::anyhow!("Failed to encode EAP-Notification: {}", e))?;
                Ok(ActionResult::Output(
                    codec::eapol_wrap_eap(ctx.eapol_version, &eap)
                        .map_err(|e| anyhow::anyhow!("Failed to encode EAPOL frame: {}", e))?,
                ))
            }

            // ---------------------------------------------------------------
            // The admission decision. The only reachable call to
            // codec::eapol_eap_success_frame in the whole crate.
            // ---------------------------------------------------------------
            "send_eap_success" => {
                if !ctx.identity_established {
                    return Err(anyhow::anyhow!(
                        "Refusing to send EAP-Success: this session has not produced an \
                         EAP-Response/Identity, so there is no identity to admit. Send \
                         send_eap_request_identity first."
                    ));
                }
                Ok(ActionResult::Output(codec::eapol_eap_success_frame(
                    ctx.eapol_version,
                    ctx.result_identifier,
                )))
            }

            "send_eap_failure" => Ok(ActionResult::Output(codec::eapol_eap_failure_frame(
                ctx.eapol_version,
                ctx.result_identifier,
            ))),

            // Unreachable: the guard above already rejected every other name. Kept as an
            // error rather than a panic, because "the two lists drifted apart" must not be a
            // way to crash a running authenticator.
            other => Err(anyhow::anyhow!("Unknown EAPOL action: {}", other)),
        }
    }
}
