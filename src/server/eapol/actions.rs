/// EAPOL authenticator.
///
/// The registry holds a context-free instance from [`EapolProtocol::new`]; it can describe the
/// vocabulary but cannot encode a single frame, because every frame needs an EAP identifier
/// that only a received packet can supply. `mod.rs` builds one instance **per received frame**
/// with [`EapolProtocol::for_request`].
pub struct EapolProtocol {
    request: Option<RequestContext>,
}

/// Everything a reply needs, taken from the frame being answered rather than from the model.
#[derive(Clone, Debug)]
pub struct RequestContext {
    /// EAPOL protocol version to echo (1..=3).
    pub eapol_version: u8,
    /// Identifier to stamp on a **new** EAP-Request. Allocated by the session, never by the
    /// model, so two overlapping exchanges cannot collide.
    pub request_identifier: u8,
    /// Identifier to stamp on an EAP-Success or EAP-Failure. RFC 3748 §4.2 requires it to
    /// match the Response being answered; a supplicant silently discards a mismatch, which
    /// looks exactly like a hang.
    pub result_identifier: u8,
    /// True only once the session holds an `EAP-Response/Identity`. Gate three on Success.
    pub identity_established: bool,
    /// Challenge NetGet generated for this exchange. The model never sees or chooses it.
    pub md5_challenge: Vec<u8>,
}

impl Default for EapolProtocol {
    fn default() -> Self {
        Self::new()
    }
}

impl EapolProtocol {
    pub fn new() -> Self {
        Self { request: None }
    }

    pub fn for_request(ctx: RequestContext) -> Self {
        Self { request: Some(ctx) }
    }

    /// The word "context" in this message is load-bearing twice over: it tells a reader why a
    /// registry instance cannot answer, and `tests/executable_examples_test.rs` keys its
    /// "needs a live request" exemption on it, exactly as `radius` does.
    fn ctx(&self) -> Result<&RequestContext> {
        self.request.as_ref().context(
            "EAPOL action executed without a request context: an EAP frame must echo the \
             identifier of the packet it answers, and this instance came from the registry \
             rather than from a received frame.",
        )
    }
}

