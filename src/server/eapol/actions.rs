/// Method types NetGet can actually put on the wire.
///
/// Refusing an unimplemented method by name is the honest answer. Quietly falling back to
/// MD5-Challenge — or worse, to a Success — would be the fail-open shape this protocol exists
/// to avoid.
fn method_type_value(v: &serde_json::Value) -> Result<u8> {
    if let Some(n) = v.as_u64() {
        let n = u8::try_from(n).context("eap_type must fit in one octet")?;
        return match n {
            codec::EAP_TYPE_MD5_CHALLENGE | codec::EAP_TYPE_TLS | codec::EAP_TYPE_PEAP => Ok(n),
            other => Err(anyhow::anyhow!(
                "EAP method type {} is not implemented by this authenticator. Implemented: \
                 4 (md5-challenge), 13 (tls), 25 (peap).",
                other
            )),
        };
    }
    let name = v
        .as_str()
        .context("eap_type must be a method name or a number")?;
    match name
        .to_ascii_lowercase()
        .replace(['-', '_', ' '], "")
        .as_str()
    {
        "md5" | "md5challenge" | "eapmd5" => Ok(codec::EAP_TYPE_MD5_CHALLENGE),
        "tls" | "eaptls" => Ok(codec::EAP_TYPE_TLS),
        "peap" => Ok(codec::EAP_TYPE_PEAP),
        other => Err(anyhow::anyhow!(
            "Unknown or unimplemented eap_type '{}'. This authenticator implements \
             'md5-challenge' (challenge generated and verified by NetGet), 'tls' and 'peap' \
             (the Start flag only — NetGet carries no TLS handshake). 'mschapv2' is \
             deliberately absent: NetGet cannot verify an MSCHAPv2 response, and offering a \
             method it cannot check would mean admitting on unverified evidence.",
            other
        )),
    }
}

fn required_text(action: &serde_json::Value, key: &str) -> Result<String> {
    action
        .get(key)
        .and_then(|v| v.as_str())
        .map(|s| s.to_string())
        .with_context(|| format!("'{}' is required and must be a string", key))
}

