//! EAPOL / 802.1X protocol vocabulary and executor.
//!
//! # Fail closed
//!
//! An `EAP-Success` frame **is** the admission decision: it is the octet that opens a switch
//! port. The OAuth2 post-mortem in the root `CLAUDE.md` — where "the LLM returned nothing"
//! fell through to a hardcoded access token, and a model's explicit denial became
//! indistinguishable from its silence — is the reason this file is shaped the way it is. It
//! copies `src/server/radius/actions.rs` deliberately, because that is the worked example the
//! repository points at.
//!
//! Four structural rules, each of which a reader can point at:
//!
//! 1. **There is no default response.** `execute_action` produces only the frame a named
//!    action asked for. Nothing here synthesises a Success.
//! 2. **Admission and denial are different actions built by different functions.**
//!    `send_eap_success` reaches [`codec::eapol_eap_success_frame`] and `send_eap_failure`
//!    reaches [`codec::eapol_eap_failure_frame`]; the two builders share no code and neither
//!    takes a parameter that could select the other.
//! 3. **A Success is impossible without an established identity.** The per-request
//!    [`RequestContext`] carries `identity_established`, set only when the session already
//!    holds an `EAP-Response/Identity`. A registry instance carries no context at all and
//!    cannot encode any frame.
//! 4. **Silence is denial, and is logged as its own thing.** When the model returns no usable
//!    action, or the LLM call fails, `mod.rs` synthesises an EAP-Failure and records
//!    `decision=fail_closed_no_action` / `decision=fail_closed_llm_error` — never
//!    `decision=model_reject`. See `EapolServer::decide`.
//!
//! # No cryptographic material comes from the model
//!
//! For MD5-Challenge the challenge is generated by NetGet (`RequestContext::md5_challenge`)
//! and the supplicant's digest is verified by NetGet (`codec::md5_response_matches`). The
//! model supplies the *password it expects*, which is ordinary structured text an operator
//! instruction naturally carries, and then decides **whether the identity is admitted**. It is
//! never asked for a hash, a nonce or a key.

